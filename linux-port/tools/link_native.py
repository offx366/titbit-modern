#!/usr/bin/env python3
"""Resolve reconstructed source aliases, then link native ELF32 objects.

Address metadata identifies equivalent source symbols; addresses are never
used as executable storage or absolute implementation definitions.
"""
import argparse
from collections import defaultdict
import json
import os
from pathlib import Path
import re
import shutil
import struct
import sys
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def decode(name):
    return bytes.fromhex(name[10:]).decode() if name.startswith('titbit_ms_') else name


def encode(name):
    return 'titbit_ms_'+name.encode().hex() if any(c in name for c in '@?\\') else name


def coff_name(name):
    raw = decode(name)
    if raw.startswith('\\01'):
        return raw[3:]
    return raw if raw.startswith('?') else '_'+raw


def nm(path):
    result = subprocess.check_output(['nm', '-g', '-P', str(path)], text=True)
    definitions, undefined = {}, []
    for line in result.splitlines():
        fields = line.split()
        if len(fields)<2: continue
        if fields[1]=='U': undefined.append(fields[0])
        else: definitions[fields[0]]=fields[1]
    return definitions, undefined


class Elf32:
    def __init__(self,path):
        self.data=Path(path).read_bytes()
        if self.data[:5]!=b'\x7fELF\x01':raise ValueError('Expected ELF32: '+str(path))
        offset=struct.unpack_from('<I',self.data,32)[0]
        size,count,strings=struct.unpack_from('<HHH',self.data,46)
        self.sections=[struct.unpack_from('<10I',self.data,offset+i*size) for i in range(count)]
        names=self.payload(strings)
        self.section_names=[names[s[0]:].split(b'\0')[0].decode() for s in self.sections]
        self.symbols={};self.symbol_index={}
        for section in self.sections:
            if section[1]!=2:continue
            names=self.payload(section[6])
            for index,at in enumerate(range(section[4],section[4]+section[5],section[9])):
                n,value,length,info,other,sec=struct.unpack_from('<IIIBBH',self.data,at)
                name=names[n:].split(b'\0')[0].decode()
                row=dict(name=name,value=value,size=length,section=sec)
                self.symbol_index[index]=row
                if name:self.symbols[name]=row
    def payload(self,index):
        s=self.sections[index];return self.data[s[4]:s[4]+s[5]]
    def locator(self,name):
        symbol=self.symbols[name]
        offset=struct.unpack_from('<I',self.payload(symbol['section']),symbol['value'])[0]
        for sec in self.sections:
            if sec[1]!=9 or sec[7]!=symbol['section']:continue
            for at in range(sec[4],sec[4]+sec[5],8):
                loc,info=struct.unpack_from('<II',self.data,at)
                if loc==symbol['value']:
                    target=self.symbol_index[info>>8]
                    return target,offset
        raise ValueError('No compiler relocation for '+name)


def sdl_libs():
    """System libSDL2, or with TITBIT_SDL2=<prefix> the static SDL2 from
    tools/build_sdl2_min.sh, which dlopens X11/Wayland/PulseAudio/ALSA itself."""
    prefix=os.environ.get('TITBIT_SDL2')
    return [str(Path(prefix)/'lib/libSDL2.a')] if prefix else ['-lSDL2']


def glu_libs():
    """libGLU is linked statically in the reduced-dependency build (libGLU.a from
    libglu1-mesa-dev:i386); only the GL driver itself stays a shared library."""
    return ['-Wl,-Bstatic','-lGLU','-Wl,-Bdynamic'] if os.environ.get('TITBIT_SDL2') else ['-lGLU']


def media_libs():
    """System FFmpeg, or with TITBIT_FFMPEG=<prefix> the minimal static build from
    tools/build_ffmpeg_min.sh (AVI + MP42 + CRAM only) plus static libstdc++,
    libgcc and zlib: the ELF then needs only libc, SDL2, GL and GLU at run time."""
    prefix=os.environ.get('TITBIT_FFMPEG')
    if not prefix:
        return ['-lavformat','-lavcodec','-lavutil','-lswscale','-lswresample','-lz']
    lib=Path(prefix)/'lib'
    return [str(lib/(n+'.a')) for n in ('libavformat','libavcodec','libswscale','libswresample','libavutil')]+[
        '-Wl,-Bstatic','-lz','-Wl,-Bdynamic','-static-libstdc++','-static-libgcc']


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--objects',type=Path,default=Path(os.environ.get('TITBIT_BUILD_DIR', ROOT/'build'))/'ms-elf/report.json')
    p.add_argument('--native',type=Path,default=Path(os.environ.get('TITBIT_BUILD_DIR', ROOT/'build'))/'native')
    p.add_argument('--out',type=Path,default=Path(os.environ.get('TITBIT_BUILD_DIR', ROOT/'build'))/'titbit')
    p.add_argument('--link',action='store_true')
    a=p.parse_args()
    config=json.loads((ROOT/'config/source-build.json').read_text())
    recipes={r['source']:r for r in config['recipes']}
    bindings={k:int(v,16) for k,v in config['bindings'].items()}
    global_aliases={r['alias']:r['provider'] for r in config['aliases']}
    # Only metadata, generated by the source build; no COFF code is consumed.
    saved=ROOT/'config/source-aliases.json'
    global_aliases.update(json.loads(saved.read_text(encoding='utf-8-sig')))
    rows=json.loads(a.objects.read_text())['rows']
    runtime_report=Path(os.environ.get('TITBIT_BUILD_DIR', ROOT/'build'))/'ms-runtime-elf/report.json'
    if runtime_report.exists():
        present={r['source'] for r in rows}
        rows += [r for r in json.loads(runtime_report.read_text())['rows'] if r['source'] not in present]
    omitted={'src/native/engine_entry_candidate.cpp','src/native/game_input.cpp',
             'src/lanes/codex/data/cxx_startup.c','src/seer/callasm.c',
             'src/lanes/codex/seer/seeR-0.94a/callasm.c'}
    rows=[r for r in rows if r['status']=='compiled' and r['source'] not in omitted]
    for path in sorted(a.native.glob('*.o')):
        defs,undef=nm(path)
        rows.append(dict(source=str(path),object=str(path),definitions=defs,undefined=undef,native=True))
    helpers=Path(os.environ.get('TITBIT_BUILD_DIR', ROOT/'build'))/'ms-runtime-elf/objects/vc6_native_helpers.o'
    if helpers.exists():
        defs,undef=nm(helpers)
        rows.append(dict(source=str(helpers),object=str(helpers),definitions=defs,undefined=undef,native=True))
    names=defaultdict(list)
    addresses=defaultdict(list)
    perunit={}
    fields={}
    def address(name,source):
        old=coff_name(name)
        local=perunit.get(source,{})
        if old in local:
            return int(local[old],16) if local[old] is not None else None
        unit=Path(source).stem+':'+old
        if unit in bindings:return bindings[unit]
        if old in bindings:return bindings[old]
        if '@?1?' in old or old.startswith(('??_','??1')):return None
        first=old.split('@',1)[0] if old.startswith('?') else old
        match=re.search(r'(?:004|005)[0-9a-fA-F]{5}',first)
        return int(match[0],16) if match else None
    for index,row in enumerate(rows):
        row['index']=index
        row['priority']=-100 if row.get('native') else recipes.get(row['source'],{}).get('priority',0)
        src=ROOT/row['source']
        spec=src.with_suffix('.bindings.json')
        local=dict(recipes.get(row['source'],{}).get('symbolAddresses',{}))
        if spec.exists():
            data=json.loads(spec.read_text());local.update(data.get('bindings',{}))
            local.update({n:None for n in data.get('unboundSymbols',[])})
            fields.update(data.get('fieldAliases',{}))
        perunit[row['source']]=local
        if not row.get('native'):
            elf=Elf32(row['object'])
            owned=set(local)
            owned.update(spec['owner'] for spec in fields.values())
            export=[]
            for old in owned:
                candidate=encode(old) if old.startswith('?') else old[1:] if old.startswith('_') else old
                symbol=elf.symbols.get(candidate)
                if (candidate not in row['definitions'] and symbol and symbol['section'] and symbol['section']<len(elf.sections)
                        and not elf.sections[symbol['section']][2]&4):
                    export.append(candidate)
                    row['definitions'][candidate]='T' if elf.sections[symbol['section']][2]&4 else 'B'
            row['globalize']=export
        for name in row['definitions']:
            names[name].append(row)
            value=address(name,row['source'])
            if value is not None:addresses[value].append((row['priority'],name,index))
    bycoff={coff_name(name):name for name in names}
    native_names={name for row in rows if row.get('native') for name in row['definitions']}
    gl=json.loads((ROOT/'platform/gl-import-map.json').read_text())['imports']
    crt={name:'tb_crt_'+name for name in ('fopen','fclose','fread','fwrite','fseek','ftell','fflush',
          'fgetc','fputc','fgets','fputs','ungetc','setvbuf','vfprintf','fprintf','feof','ferror','fileno',
          'tmpfile','stat','wcslen','itoa','fgetpos','fsetpos','rand','srand','clock')}
    crt.update({'_filbuf':'tb_crt_filbuf','_flsbuf':'tb_crt_flsbuf','_fileno':'tb_crt_fileno',
                '_filelength':'tb_crt_filelength','_errno':'tb_crt_errno','_iob':'tb_crt_iob',
                '_pctype':'tb_crt_pctype','_isctype':'tb_crt_isctype','__mb_cur_max':'tb_crt_mb_cur_max',
                '_strdup':'strdup','_itoa':'tb_crt_itoa','_purecall':'titbit_purecall'})
    crt.update({'_setjmp3':'titbit_setjmp3','longjmp':'titbit_longjmp'})
    special={'??2@YAPAXI@Z':'titbit_operator_new','??3@YAXPAX@Z':'titbit_operator_delete',
             '??_U@YAPAXI@Z':'titbit_operator_new','??_V@YAXPAX@Z':'titbit_operator_delete',
             '??_7type_info@@6B@':'titbit_type_info_vtable'}
    special.update({'??_C@_00A@?$AA@':'titbit_empty_text',
                    '??_B?1???id@?$ctype@G@std@@$D@@9@51':'titbit_iostream_setup_guard'})
    for old,value in bindings.items():
        if old.startswith('?') and '@@3' in old:
            plain=old[1:].split('@')[0]
            if plain in native_names:addresses[value].append((-100,plain,-1))
        if old in special:addresses[value].append((-100,special[old],-1))
    def visibility_key(old):
        return re.sub(r'(@@)[AQIE](?=[AB][EG])',r'\1Q',old)
    visibility={visibility_key(coff_name(n)):n for n in names}
    field_targets={}
    field_proofs={}
    for old,spec in fields.items():
        locator=spec['locator'].lstrip('_')
        locators=names.get(locator,[])
        for row in locators:
            locator_elf=Elf32(row['object'])
            target,offset=locator_elf.locator(locator)
            owner=bycoff.get(spec['owner'])
            owner_symbol=locator_elf.symbols.get(owner)
            matched=target['name']==owner
            if not matched and owner_symbol and target['section']==owner_symbol['section'] and target['section']:
                offset+=target['value']-owner_symbol['value'];matched=True
            if owner and matched:
                alias=encode(old) if old.startswith('?') else old[1:]
                field_targets[alias]=(owner,offset)
                value=address(alias,row['source'])
                value=bindings.get(old,value)
                if value is None:
                    value=next((int(local[old],16) for local in perunit.values() if local.get(old)),None)
                if value is not None:addresses[value].append((-1,alias,-1))
            field_proofs[old]={'sourceLocator':locator,'owner':spec['owner'],'compilerOffset':offset,'resolved':matched}
            break
    def resolve(name,source):
        raw=decode(name)
        old=coff_name(name)
        if raw in crt:return crt[raw]
        if old in special:return special[old]
        if raw.startswith('\\01_'):
            plain=raw[4:].split('@')[0]
            return gl.get(plain,plain)
        if old in global_aliases:
            target=global_aliases[old]
            if target in special:return special[target]
            if target in bycoff:return bycoff[target]
            if target.startswith('?') and '@@3' in target:
                plain=target[1:].split('@')[0]
                if plain in native_names:return plain
            if target.startswith('_') and '@' not in target and '?' not in target:
                plain=target[1:]
                return crt.get(plain,plain)
        if visibility_key(old) in visibility:return visibility[visibility_key(old)]
        value=address(name,source)
        if value in addresses:
            return min(addresses[value])[1]
        # GNU C++ globals at namespace scope have their ordinary names, while
        # the Microsoft ABI decorates the same source variable's type.
        if raw.startswith('?') and '@@3' in raw:
            plain=raw[1:].split('@')[0]
            if plain in native_names:return plain
        return None
    aliases={}
    unresolved=defaultdict(list)
    for row in rows:
        for name in row['undefined']:
            if name in names:continue
            target=resolve(name,row['source'])
            if target and target!=name:aliases[name]=target
            else:unresolved[decode(name)].append(row['source'])
    outinfo={'objects':len(rows),'aliases':aliases,'unresolved':dict(sorted(unresolved.items())),
             'fieldProofs':field_proofs}
    a.native.mkdir(parents=True,exist_ok=True)
    (a.native/'link-plan.json').write_text(json.dumps(outinfo,indent=2))
    script=a.native/'aliases.ld'
    roots={target for target in aliases.values() if target in names}
    roots.update(owner for owner,offset in field_targets.values())
    script.write_text('EXTERN('+ ' '.join(sorted(roots))+')\n'+
                      '\n'.join(f'PROVIDE({name} = {target});' for name,target in sorted(aliases.items()))+'\n'+
                      '\n'.join(f'PROVIDE({name} = {owner} + {offset});' for name,(owner,offset) in field_targets.items())+'\n')
    if a.link:
        adapted=a.native/'adapted';adapted.mkdir(exist_ok=True)
        for row in rows:
            source=Path(row['object']);dest=adapted/source.name
            shutil.copy2(source,dest)
            changes={} if row.get('native') else {name:aliases[name] for name in row['undefined'] if name in aliases}
            grouped=defaultdict(list)
            for name,target in changes.items():grouped[target].append(name)
            for round in range(max((len(v) for v in grouped.values()),default=0)):
                arguments=[]
                for target,symbols in grouped.items():
                    if len(symbols)>round:arguments+=['--redefine-sym',symbols[round]+'='+target]
                subprocess.run(['objcopy',*arguments,str(dest)],check=True)
            arguments=[]
            for name in row.get('globalize',[]):arguments+=['--globalize-symbol',name]
            fields_here={field:(owner,offset) for field,(owner,offset) in field_targets.items() if owner in row['definitions']}
            if fields_here:
                elf=Elf32(source)
                for field,(owner,offset) in fields_here.items():
                    symbol=elf.symbols[owner]
                    arguments+=['--add-symbol',field+'='+elf.section_names[symbol['section']]+':'+str(symbol['value']+offset)+',global,object']
            if arguments:subprocess.run(['objcopy',*arguments,str(dest)],check=True)
            row['object']=str(dest)
        from elf_comdat import select_comdats
        outinfo['comdatSelections']=select_comdats(rows)
        game=[r for r in rows if not r.get('native') and not r['source'].startswith(('platform/','src/linux_runtime/'))]
        direct=[r for r in rows if r not in game]
        archive=a.native/'game.a'
        archive.unlink(missing_ok=True)
        subprocess.run(['llvm-ar-18','rcs',str(archive),*[r['object'] for r in sorted(game,key=lambda r:r['priority'])]],check=True)
        command=['clang++-18','-m32','-no-pie','-Wl,--gc-sections',
                 '-Wl,-Map,'+str(a.native/'titbit.map'),
                 *[r['object'] for r in direct],'-Wl,--start-group',str(archive),'-Wl,--end-group','-L/usr/lib/i386-linux-gnu',
                 *sdl_libs(),*glu_libs(),'-lGL',*media_libs(),'-lpthread','-ldl','-lm','-o',str(a.out.with_suffix('.new'))]
        # INSERT lets the native linker keep its standard ELF layout.
        script.write_text(script.read_text()+'SECTIONS { .titbit_metadata : { } } INSERT AFTER .rodata;\n')
        result=subprocess.run(command,capture_output=True,text=True)
        (a.native/'link.log').write_text(result.stdout+result.stderr)
        print((result.stdout+result.stderr)[-6000:])
        outinfo['linked']=result.returncode==0
        if result.returncode==0:a.out.with_suffix('.new').replace(a.out)
        else:a.out.with_suffix('.new').unlink(missing_ok=True)
        (a.native/'link-plan.json').write_text(json.dumps(outinfo,indent=2))
    print(json.dumps({'objects':len(rows),'aliases':len(aliases),'unresolved':len(unresolved)}))
    return 1 if a.link and not outinfo.get('linked') else 0


if __name__=='__main__':sys.exit(main())
